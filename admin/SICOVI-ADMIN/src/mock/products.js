// Datos de ejemplo -- misma forma que devuelve GET /api/products (rol admin,
// con precioCosto/margen incluidos). Nombres tomados de la factura real de
// SIGLO 2000 que se usó como referencia para el modelo de Producto.
import { categories } from './categories'
import { suppliers } from './suppliers'

const cat = (nombre) => {
  const c = categories.find((c) => c.nombre === nombre)
  return { _id: c._id, nombre: c.nombre }
}
const sup = (nombre) => {
  const s = suppliers.find((s) => s.nombre.startsWith(nombre))
  return { _id: s._id, nombre: s.nombre }
}

function conMargen(p) {
  const margen = Number((p.precioVenta - p.precioCosto).toFixed(2))
  const margenPorcentaje = p.precioVenta ? Number(((margen / p.precioVenta) * 100).toFixed(2)) : 0
  return { ...p, margen, margenPorcentaje }
}

